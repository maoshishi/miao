  function parse(list) {
    var out = [];
    for (var i = 0; i < list.length; i++) {
      var parts = String(list[i]).split('|');
      if (parts.length !== 2) continue;
      var a = parts[0].trim(), b = parts[1].trim();
      // 防御：接龙必须首尾同字，长度都按 4 字成语处理
      if (a.length !== 4 || b.length !== 4) continue;
      if (a.charAt(3) !== b.charAt(0)) continue;
      out.push([a, b]);
    }
    return out;
  }

  var packs = { easy: parse(EASY), hard: parse(HARD), expert: parse(EXPERT) };

  // 干扰项池
  var pool = [];
  (function () {
    var seen = {};
    function push(w) { if (w.length === 4 && !seen[w]) { seen[w] = 1; pool.push(w); } }
    for (var k in packs) {
      for (var i = 0; i < packs[k].length; i++) { push(packs[k][i][0]); push(packs[k][i][1]); }
    }
    for (var j = 0; j < EXTRA_POOL.length; j++) push(EXTRA_POOL[j]);
  })();

  /* 出题：给定难度，返回 {ask, answer, options:[4个]}
     选项里一定只有一个的首字 = ask 的末字 */
  function makeQuestion(tier) {
    var list = packs[tier] || packs.easy;
    if (!list.length) list = packs.easy;

    for (var attempt = 0; attempt < 40; attempt++) {
      var pair = list[(Math.random() * list.length) | 0];
      var ask = pair[0], answer = pair[1];
      var key = ask.charAt(3);

      var wrong = [];
      var guard = 0;
      while (wrong.length < 3 && guard++ < 800) {
        var cand = pool[(Math.random() * pool.length) | 0];
        if (!cand || cand === answer) continue;
        if (cand.charAt(0) === key) continue;       // 首字相同就不算干扰项
        if (cand === ask) continue;
        if (wrong.indexOf(cand) >= 0) continue;
        wrong.push(cand);
      }
      if (wrong.length < 3) continue;

      var opts = wrong.concat([answer]);
      for (var i = opts.length - 1; i > 0; i--) {
        var j = (Math.random() * (i + 1)) | 0;
        var t = opts[i]; opts[i] = opts[j]; opts[j] = t;
      }
      return { ask: ask, answer: answer, key: key, options: opts };
    }
    return null;
  }

  return { packs: packs, makeQuestion: makeQuestion };
